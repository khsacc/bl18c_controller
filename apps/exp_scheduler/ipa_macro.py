"""IPAnalyzer batch-integration macro for one run's XRD images.

The macro lists the images recorded in the run's xrd_master.csv, in
acquisition order, so it never has to rebuild filenames from the suffix
rules. It is rewritten after every saved XRD image, so it stays complete even
when a run stops early.

Sections are ordered settings → processing → images → loop so the editable
parameters stay at the top even when the image list is long.

IPAnalyzer API names were checked against seto77/IPAnalyzer Macro.cs (2026-10):
'Find spots before Get Profile' is `IPA.Profile.MaskSpotsBeforeGetProfile`
(older macros used `FindSpotsBeforeGetProfile`), and `IPA.File.ReadImage`
opens a file dialog when the path does not exist, so only existing images
are listed.

Standalone use (regenerate for an existing run):
    python -m apps.exp_scheduler.ipa_macro <run>/XRD
"""
from __future__ import annotations

import csv
import math
import os
import sys
from datetime import datetime
from pathlib import Path

from .xrd_master import MASTER_FILENAME

DEVELOPER_LINE = "# Developer: Hiroki Kobayashi (UTokyo, 2026)"


def macro_filename(run_name: str) -> str:
    return f"IPAnalyzer_analysis_macro_{run_name}.mcr"


def _number(text) -> float | None:
    try:
        value = float(text)
    except (TypeError, ValueError):
        return None
    return value if math.isfinite(value) else None


def _quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _row_note(row: dict) -> str:
    """`2026-10-25 14:03:11  P 0.520 MPa  TB 300.1 K` from one master row."""
    parts = []
    start = row.get("start_time") or ""
    try:
        parts.append(datetime.fromisoformat(start).strftime("%Y-%m-%d %H:%M:%S"))
    except ValueError:
        pass
    pressure = _number(row.get("pressure_start_MPa"))
    if pressure is not None:
        parts.append(f"P {pressure:.3f} MPa")
    for axis in ("a", "b"):
        temp = _number(row.get(f"temperature_{axis}_mean_K"))
        if temp is None:
            temp = _number(row.get(f"temperature_{axis}_start_K"))
        if temp is not None:
            parts.append(f"T{axis.upper()} {temp:.1f} K")
    return "  ".join(parts)


def _read_rows(xrd_dir: Path) -> list[dict]:
    """Master rows whose image still exists, in acquisition order."""
    master = xrd_dir / MASTER_FILENAME
    if not master.is_file():
        return []
    with master.open("r", newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.DictReader(handle))
    return [row for row in rows
            if row.get("xrd_file") and (xrd_dir / row["xrd_file"]).is_file()]


_HEADER = """\
# IPAnalyzer macro: 1D profiles for every XRD image of one scheduler run
{developer}
# Auto-generated by the BL-18C Experimental Scheduler for run '{run}'.
# Updated {updated} ({count} images). The scheduler rewrites this file each
# time it saves an XRD image, so save edited copies under another name.
# Open in IPAnalyzer: Macro > Load, then Run. Set wavelength, detector
# geometry and integration range in IPAnalyzer before running.

# ============================== settings ==============================
# True saves a profile file for each image.
SAVE_PROFILE = True
# Profile file format: "GSAS", "CSV", "TSV" or "PDI".
PROFILE_FORMAT = "GSAS"
# True asks for an output folder; False saves next to the images.
ASK_OUTPUT_DIR = True
# True sends each profile to PDIndexer via the clipboard.
SEND_TO_PDINDEXER = True
# True runs 'Find center' before each profile (normally False for the FPD).
FIND_CENTER = False
# True runs 'Find spots' (mask spots) before each profile.
FIND_SPOTS = False
# True asks once for a mask file (*.mas) and applies it to every image.
READ_MASK = False

# ============================= processing =============================
EXTENSIONS = {{"GSAS": ".gsa", "CSV": ".csv", "TSV": ".tsv", "PDI": ".pdi"}}

imageDir = IPA.File.GetDirectoryPath()  # choose this XRD folder
outDir = imageDir
if ASK_OUTPUT_DIR and imageDir != "":
    outDir = IPA.File.GetDirectoryPath()  # choose the output folder
maskFile = ""
if READ_MASK and imageDir != "":
    maskFile = IPA.File.GetFileName("Select mask file (*.mas)")

IPA.Profile.FindCenterBeforeGetProfile = FIND_CENTER
IPA.Profile.MaskSpotsBeforeGetProfile = FIND_SPOTS
IPA.Profile.SendProfileViaClipboard = SEND_TO_PDINDEXER
IPA.Profile.SaveProfileAfterGetProfile = SAVE_PROFILE
if PROFILE_FORMAT == "GSAS":
    IPA.Profile.SaveProfileAsGSAS = True
elif PROFILE_FORMAT == "CSV":
    IPA.Profile.SaveProfileAsCSV = True
elif PROFILE_FORMAT == "TSV":
    IPA.Profile.SaveProfileAsTSV = True
elif PROFILE_FORMAT == "PDI":
    IPA.Profile.SaveProfileAsPDI = True

# =============================== images ===============================
# Acquisition order (from {master}). Comment out a line to skip that image.
"""

_LOOP = """\

# ================================ run =================================
# Nothing is processed if a folder or mask dialog was cancelled.
if imageDir != "" and outDir != "" and not (READ_MASK and maskFile == ""):
    for name in FILES:
        IPA.File.ReadImage(imageDir + name)
        if maskFile != "":
            IPA.IntegralProperty.ReadMask(maskFile)
        if SAVE_PROFILE:
            IPA.Profile.GetProfile(outDir + name[:-4] + EXTENSIONS[PROFILE_FORMAT])
        else:
            IPA.Profile.GetProfile()
"""


def build_macro(run_name: str, rows: list[dict], updated: datetime | None = None) -> str:
    updated = updated or datetime.now()
    names = [_quote(row["xrd_file"]) + "," for row in rows]
    width = max((len(name) for name in names), default=0)
    lines = ["FILES = ["]
    for name, row in zip(names, rows):
        note = _row_note(row)
        lines.append(f"    {name.ljust(width)}  # {note}" if note else f"    {name}")
    lines.append("]")
    header = _HEADER.format(
        developer=DEVELOPER_LINE, run=run_name,
        updated=updated.strftime("%Y-%m-%d %H:%M:%S"),
        count=len(rows), master=MASTER_FILENAME,
    )
    return header + "\n".join(lines) + "\n" + _LOOP


def write_ipa_macro(xrd_dir: Path) -> Path:
    """(Re)write <xrd_dir>/IPAnalyzer_analysis_macro_<run>.mcr; return its path.

    The run name is the run directory's name (the parent of XRD/). Written
    with Windows line endings and replaced atomically."""
    xrd_dir = Path(xrd_dir)
    run_name = xrd_dir.resolve().parent.name
    path = xrd_dir / macro_filename(run_name)
    text = build_macro(run_name, _read_rows(xrd_dir))
    tmp = path.with_name(path.name + ".tmp")
    with tmp.open("w", encoding="utf-8", newline="\r\n") as handle:
        handle.write(text)
    os.replace(tmp, path)
    return path


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python -m apps.exp_scheduler.ipa_macro <run>/XRD")
    print(write_ipa_macro(Path(sys.argv[1])))
